CREATE DATABASE IF NOT EXISTS asabri_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE asabri_db;

CREATE TABLE IF NOT EXISTS data_contact (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nama VARCHAR(100) NOT NULL,
    nomor VARCHAR(20) NOT NULL,
    subject VARCHAR(150) NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS faq (
    id INT AUTO_INCREMENT PRIMARY KEY,
    kategori VARCHAR(50) NOT NULL,
    pertanyaan VARCHAR(255) NOT NULL,
    jawaban TEXT NOT NULL,
    kata_kunci VARCHAR(255) NOT NULL DEFAULT '',
    sumber VARCHAR(100) NOT NULL DEFAULT ''
);
